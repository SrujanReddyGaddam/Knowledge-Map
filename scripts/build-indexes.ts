// Regenerates the lists inside hub notes from frontmatter, so hubs and index.md never go stale.
//
//   node scripts/build-indexes.ts <vault-path> [--check]
//
// In any note, write a marker pair; everything between them is replaced on each run:
//   <!-- km:list type=bug customer=acme folder=knowledge/uipath group=type sort=updated limit=50 -->
//   <!-- km:end -->
// Filters: any frontmatter key=value (a,b = either; list fields like tags match any item), folder=<path prefix>.
// group=<key> or group=folder adds a ### heading per value. sort=title (default) | updated. The note itself is never listed.
// Skips dot-folders, _templates/, sources/ and the scaffold files at the vault root (README, CLAUDE, AGENTS, PLAN, TODO, WORKLOG). Markers inside code blocks are left alone. Writes only files whose text changes (temp file + rename). --check writes nothing and exits 1 if anything is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { parseFrontmatter } from '../frontmatter.ts';

const root = process.argv[2], check = process.argv.includes('--check');
if (!root || !fs.existsSync(root)) { console.error('usage: node scripts/build-indexes.ts <vault-path> [--check]'); process.exit(2); }

const SCAFFOLD = new Set(['README.md', 'CLAUDE.md', 'AGENTS.md', 'PLAN.md', 'TODO.md', 'WORKLOG.md']);
type N = { rel: string; base: string; fm: Record<string, any>; text: string; mtime: number };
const notes: N[] = [];
(function walk(dir: string) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || e.name === 'node_modules') continue;
    const p = path.join(dir, e.name), rel = path.relative(root, p).split(path.sep).join('/');
    if (e.isDirectory()) { if (rel !== '_templates') walk(p); continue; }
    if (!/\.md$/i.test(e.name) || /\.excalidraw\.md$/i.test(e.name) || (dir === root && SCAFFOLD.has(e.name))) continue;
    const text = fs.readFileSync(p, 'utf8');
    notes.push({ rel, base: e.name.replace(/\.md$/i, ''), fm: parseFrontmatter(text).fm, text, mtime: fs.statSync(p).mtimeMs });
  }
})(root);

const vals = (v: unknown) => (Array.isArray(v) ? v : String(v ?? '').split(',')).map(x => String(x).trim().toLowerCase().replace(/^\[\[|\]\]$/g, '')).filter(Boolean);
const MARK = /<!-- km:list([^>]*?)-->[\s\S]*?<!-- km:end -->/g;

function render(args: string, self: N) {
  const opt: Record<string, string> = {};
  for (const m of args.matchAll(/([\w-]+)=("[^"]*"|\S+)/g)) opt[m[1].toLowerCase()] = m[2].replace(/^"|"$/g, '');
  const { folder, group, sort, limit, ...filters } = opt;
  let list = notes.filter(n => n !== self && !n.rel.startsWith('sources/')
    && (!folder || n.rel.startsWith(folder.replace(/\/?$/, '/')))
    && Object.entries(filters).every(([k, v]) => { const want = vals(v), have = vals(n.fm[k]); return want.some(w => have.includes(w)); }));
  list.sort(sort === 'updated' ? (a, b) => b.mtime - a.mtime : (a, b) => String(a.fm.title || a.base).localeCompare(String(b.fm.title || b.base)));
  if (limit) list = list.slice(0, Number(limit) || list.length);
  const line = (n: N) => `- [[${n.base}]]` + (n.fm.summary ? `: ${String(n.fm.summary).replace(/\s+/g, ' ').trim()}` : n.fm.title ? `: ${n.fm.title}` : '');
  let out: string[];
  if (!list.length) out = ['_(nothing matches yet)_'];
  else if (group) {
    const key = (n: N) => (group === 'folder' ? n.rel.split('/').slice(0, -1).join('/') || '(root)' : vals(n.fm[group])[0] || '(none)');
    const groups = new Map<string, N[]>();
    list.forEach(n => groups.set(key(n), [...(groups.get(key(n)) || []), n]));
    out = [...groups].sort((a, b) => a[0].localeCompare(b[0])).flatMap(([g, ns]) => ['', `### ${g}`, '', ...ns.map(line)]);
    out.shift();
  } else out = list.map(line);
  return `<!-- km:list${args}-->\n<!-- generated by scripts/build-indexes.ts, edits between these markers are overwritten -->\n${out.join('\n')}\n<!-- km:end -->`;
}

let changed = 0, hubs = 0;
for (const n of notes) {
  if (!n.text.includes('<!-- km:list')) continue;
  hubs++;
  // code blocks (e.g. a README showing the marker syntax) are cut out first and put back unchanged
  const fences: string[] = [];
  const masked = n.text.replace(/^(```|~~~)[\s\S]*?^\1/gm, m => `\u0000${fences.push(m) - 1}\u0000`);
  const next = masked.replace(MARK, (_, args: string) => render(args, n)).replace(/\u0000(\d+)\u0000/g, (_, i) => fences[Number(i)]);
  if (next === n.text) continue;
  changed++;
  console.log((check ? 'out of date: ' : 'updated: ') + n.rel);
  if (check) continue;
  const abs = path.join(root, n.rel), tmp = path.join(path.dirname(abs), `.${path.basename(abs)}.km-tmp-${process.pid}`);
  fs.writeFileSync(tmp, next, { flag: 'wx', mode: fs.statSync(abs).mode & 0o777 });
  fs.renameSync(tmp, abs);
}
console.log(`${hubs} notes with lists, ${changed} ${check ? 'out of date' : 'updated'}`);
process.exit(check && changed ? 1 : 0);
